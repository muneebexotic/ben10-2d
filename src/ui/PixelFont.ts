interface GlyphRect {
  char: string;
  x: number;
  y: number;
  w: number;
}

export function registerPixelFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.exists(FONT_KEY)) return;

  const chars = Object.keys(GLYPHS);
  const cellH = GLYPH_H + 2;
  const perRow = 16;
  const rows = Math.ceil(chars.length / perRow);
  const layout: GlyphRect[] = [];
  let maxRowWidth = 0;
  for (let r = 0; r < rows; r++) {
    let x = 0;
    for (const char of chars.slice(r * perRow, (r + 1) * perRow)) {
      const w = GLYPHS[char][0].length;
      layout.push({ char, x, y: r * (cellH + 1), w });
      x += w + 3;
    }
    maxRowWidth = Math.max(maxRowWidth, x);
  }

  const texW = maxRowWidth;
  const texH = rows * (cellH + 1);
  const canvasTex = scene.textures.createCanvas(FONT_KEY, texW, texH);
  if (!canvasTex) return;
  const ctx = canvasTex.getContext();

  const fill = (x: number, y: number, color: string) => {
    ctx.fillStyle = color;
    ctx.fillRect(x, y, 1, 1);
  };
  const outlineCss = `#${OUTLINE.toString(16).padStart(6, '0')}`;

  for (const g of layout) {
    const rowsData = GLYPHS[g.char];
    const on = (gx: number, gy: number) =>
      gy >= 0 && gy < GLYPH_H && gx >= 0 && gx < g.w && rowsData[gy][gx] === '#';
    for (let gy = -1; gy <= GLYPH_H; gy++) {
      for (let gx = -1; gx <= g.w; gx++) {
        if (on(gx, gy)) continue;
        let near = false;
        for (let dy = -1; dy <= 1 && !near; dy++) for (let dx = -1; dx <= 1 && !near; dx++) near = on(gx + dx, gy + dy);
        if (near) fill(g.x + gx + 1, g.y + gy + 1, outlineCss);
      }
    }
    for (let gy = 0; gy < GLYPH_H; gy++) for (let gx = 0; gx < g.w; gx++) if (on(gx, gy)) fill(g.x + gx + 1, g.y + gy + 1, '#ffffff');
  }
  canvasTex.refresh();

  const glyphData: Record<number, unknown> = {};
  for (const g of layout) {
    const w = g.w + 2;
    const entry = {
      x: g.x,
      y: g.y,
      width: w,
      height: cellH,
      centerX: Math.floor(w / 2),
      centerY: Math.floor(cellH / 2),
      xOffset: 0,
      yOffset: 0,
      xAdvance: g.w + 1,
      data: {},
      kerning: {},
      u0: g.x / texW,
      v0: 1 - g.y / texH,
      u1: (g.x + w) / texW,
      v1: 1 - (g.y + cellH) / texH,
    };
    glyphData[g.char.charCodeAt(0)] = entry;
    const lower = g.char.toLowerCase();
    if (lower !== g.char) glyphData[lower.charCodeAt(0)] = entry;
  }

  const data = { font: FONT_KEY, size: FONT_SIZE, lineHeight: cellH + 2, chars: glyphData };
  scene.cache.bitmapFont.add(FONT_KEY, { data, texture: FONT_KEY, frame: null });
}
