"""The HUD's pieces and pickups from the owner's second HUD sheet (docs/art-refs/hud-props.webp): hearts, the
Omnitrix dial ring, the collectible card, the checkpoint post, the smoothie, the drone and boss icons. Each drawing
as it is, fitted (aspect kept) into its pixel texture's frame at T texels a game px; a group shares one scale so its
frames match (the post lit and unlit). Writes public/assets/cast/hud-props.webp and
src/scenes/preload/cartoon/cutout/hudProps.ts (frames `body:<texture>:<frame>`).

    python3 -I scripts/cutout/hud_props.py
"""
import json
import os
import sys

import cv2
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from cut import ROOT, figure_rgba  # noqa: E402

SHEET = 'docs/art-refs/hud-props.webp'
T = 6
# Each piece by where it is on the sheet (a point inside it, sheet px).
AT = {
    'heart0': (240, 220), 'heart1': (745, 220), 'heart2': (1250, 220), 'dial': (1750, 225),
    'card0': (245, 670), 'card1': (748, 670), 'post0': (1252, 890), 'post1': (1752, 890),
    'smoothy': (245, 1120), 'drone': (745, 1115), 'boss': (1005, 1115),
}
# Groups: the pixel texture (frame size in game px, frames in order, aligned to the bottom or the middle).
GROUPS = [
    ('ui-heart', 9, 8, ['heart0', 'heart1', 'heart2'], 'middle'),
    ('ui-dial', 44, 44, ['dial'], 'middle'),
    ('ui-card', 9, 11, ['card0', 'card1'], 'middle'),
    ('prop-checkpoint', 13, 29, ['post0', 'post1'], 'bottom'),
    ('pickup-smoothy', 14, 19, ['smoothy'], 'bottom'),
    ('ui-drone', 11, 8, ['drone'], 'middle'),
    ('ui-boss', 14, 10, ['boss'], 'middle'),
]

raw = cv2.cvtColor(cv2.imread(os.path.join(ROOT, SHEET)), cv2.COLOR_BGR2RGB)
H, W = raw.shape[:2]
fig = figure_rgba(raw, (0, 0, W, H), 240)
solid = (fig[..., 3] > 0.3).astype(np.uint8)
n, lab, stats, _ = cv2.connectedComponentsWithStats(cv2.dilate(solid, np.ones((15, 15), np.uint8)))


def piece(name):
    x, y = AT[name]
    k = lab[y, x]
    assert k > 0, f'{name}: nothing at {AT[name]}'
    bx, by, bw, bh, _ = stats[k]
    crop = fig[by:by + bh, bx:bx + bw] * (lab[by:by + bh, bx:bx + bw] == k)[..., None]
    return crop


tiles, frames = [], {}
for key, gw, gh, names, align in GROUPS:
    crops = [piece(nm) for nm in names]
    # One scale for the group: the biggest member fits the frame.
    s = min(min(gw * T / c.shape[1], gh * T / c.shape[0]) for c in crops)
    for i, c in enumerate(crops):
        w, h = max(1, round(c.shape[1] * s)), max(1, round(c.shape[0] * s))
        small = cv2.resize(c, (w, h), interpolation=cv2.INTER_AREA)
        tile = np.zeros((gh * T, gw * T, 4), np.float32)
        ox = (gw * T - w) // 2
        oy = gh * T - h if align == 'bottom' else (gh * T - h) // 2
        tile[oy:oy + h, ox:ox + w] = small
        tiles.append((f'body:{key}:{i}', tile))

# Pack in one row-wrapped strip.
MAXW = 1024
x = y = rowh = 0
placed = []
for name, t in tiles:
    h, w = t.shape[:2]
    if x + w > MAXW:
        x, y, rowh = 0, y + rowh + 2, 0
    placed.append((name, x, y, t))
    x += w + 2
    rowh = max(rowh, h)
atlas = np.zeros((y + rowh, MAXW, 4), np.float32)
for name, px, py, t in placed:
    h, w = t.shape[:2]
    atlas[py:py + h, px:px + w] = t
    frames[name] = {'x': px, 'y': py, 'w': w, 'h': h, 'px': 0, 'py': 0}
a = atlas[..., 3:]
rgb = np.where(a > 0, atlas[..., :3] / np.maximum(a, 1e-6), 0)
out = np.dstack([np.clip(rgb, 0, 255), np.clip(a * 255, 0, 255)]).astype(np.uint8)
out_img = os.path.join(ROOT, 'public', 'assets', 'cast', 'hud-props.webp')
cv2.imwrite(out_img, cv2.cvtColor(out, cv2.COLOR_RGBA2BGRA), [cv2.IMWRITE_WEBP_QUALITY, 92])
out_ts = os.path.join(ROOT, 'src', 'scenes', 'preload', 'cartoon', 'cutout', 'hudProps.ts')
with open(out_ts, 'w') as fh:
    fh.write('// Generated by scripts/cutout/hud_props.py: do not edit.\n')
    fh.write("import type { CutoutMeta } from './cutout';\n\n")
    fh.write('export const HUD_PROPS: CutoutMeta = {\n')
    for key, v in (('id', 'hud-props'), ('image', 'assets/cast/hud-props.webp'), ('texel', T), ('scale', 1), ('headScale', 1), ('width', MAXW), ('height', out.shape[0])):
        fh.write(f'  {key}: {json.dumps(v)},\n')
    fh.write('  joints: {},\n  frames: {\n')
    for k, v in frames.items():
        fh.write(f'    {json.dumps(k)}: {json.dumps(v, separators=(", ", ": "))},\n')
    fh.write('  },\n  bends: {},\n};\n')
print(f'{len(frames)} frames, atlas {MAXW}x{out.shape[0]} -> {out_img}')
