"""The HUD's character icons from the owner's icon sheet (docs/art-refs/hud-icons.webp): each round icon as it is,
shrunk to SIZE texels and packed in a row-major grid. Writes public/assets/cast/hud-icons.webp and
src/scenes/preload/cartoon/cutout/hudIcons.ts (a CutoutMeta, one frame per character: `body:<id>`).

    python3 -I scripts/cutout/hud_icons.py
"""
import json
import os
import sys

import cv2
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import frames as F  # noqa: E402
from cut import ROOT  # noqa: E402

SHEET = 'docs/art-refs/hud-icons.webp'
# The sheet's order: left to right, top to bottom.
IDS = ['ben', 'gwen', 'heatblast', 'wildmutt', 'diamondhead', 'xlr8', 'greymatter', 'fourarms', 'stinkfly', 'ripjaws', 'upgrade', 'ghostfreak']
# Texels a side: a 16-px icon at the HD look's sharpest (6 texels a game px).
SIZE = 96
COLS = 4

figs = F.figures(F.read_sheet(SHEET), 240, 15000, 7)
assert len(figs) == len(IDS), f'{len(figs)} icons on the sheet, {len(IDS)} expected'
rows = (len(IDS) + COLS - 1) // COLS
atlas = np.zeros((rows * SIZE, COLS * SIZE, 4), np.uint8)
frames = {}
for i, (cid, f) in enumerate(zip(IDS, figs)):
    a = f[..., 3:]
    rgb = np.where(a > 0, f[..., :3] / np.maximum(a, 1e-6), 0)
    # Square, centred on the circle.
    h, w = a.shape[:2]
    side = max(h, w)
    sq = np.zeros((side, side, 4), np.float32)
    oy, ox = (side - h) // 2, (side - w) // 2
    sq[oy:oy + h, ox:ox + w, :3] = rgb * a
    sq[oy:oy + h, ox:ox + w, 3:] = a
    small = cv2.resize(sq, (SIZE, SIZE), interpolation=cv2.INTER_AREA)
    alpha = small[..., 3:]
    colour = np.where(alpha > 0, small[..., :3] / np.maximum(alpha, 1e-6), 0)
    x, y = (i % COLS) * SIZE, (i // COLS) * SIZE
    atlas[y:y + SIZE, x:x + SIZE, :3] = np.clip(colour, 0, 255).astype(np.uint8)
    atlas[y:y + SIZE, x:x + SIZE, 3] = np.clip(alpha[..., 0] * 255, 0, 255).astype(np.uint8)
    frames['body:' + cid] = {'x': x, 'y': y, 'w': SIZE, 'h': SIZE, 'px': SIZE / 2, 'py': SIZE / 2}

out_img = os.path.join(ROOT, 'public', 'assets', 'cast', 'hud-icons.webp')
cv2.imwrite(out_img, cv2.cvtColor(atlas, cv2.COLOR_RGBA2BGRA), [cv2.IMWRITE_WEBP_QUALITY, 92])
out_ts = os.path.join(ROOT, 'src', 'scenes', 'preload', 'cartoon', 'cutout', 'hudIcons.ts')
with open(out_ts, 'w') as fh:
    fh.write('// Generated by scripts/cutout/hud_icons.py: do not edit.\n')
    fh.write("import type { CutoutMeta } from './cutout';\n\n")
    fh.write('export const HUD_ICONS: CutoutMeta = {\n')
    for key, v in (('id', 'hud-icons'), ('image', 'assets/cast/hud-icons.webp'), ('texel', SIZE), ('scale', 1), ('headScale', 1), ('width', atlas.shape[1]), ('height', atlas.shape[0])):
        fh.write(f'  {key}: {json.dumps(v)},\n')
    fh.write('  joints: {},\n  frames: {\n')
    for k, v in frames.items():
        fh.write(f'    {json.dumps(k)}: {json.dumps(v, separators=(", ", ": "))},\n')
    fh.write('  },\n  bends: {},\n};\n')
print(f'{len(IDS)} icons, atlas {atlas.shape[1]}x{atlas.shape[0]} -> {out_img}')
